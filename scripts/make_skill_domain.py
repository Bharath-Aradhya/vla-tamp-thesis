"""Generate pddl/domain_skills.pddl: the planning domain as the SCRIPTED SKILLS can actually execute it.

Run from the project root:  python scripts/make_skill_domain.py

The hand-written domain (pddl/domain.pddl) says what the robot could do in principle. The measured interference
experiments (results/interference_*.csv, results/approach_*.csv, results/dense_*.csv) say which of those actions the
scripted skills can do reliably when other bars stand close by. This script turns the measurements into planner
preconditions, one pick/place action per slot, so the planner avoids the situations the skills fail in:

  sliding rule   pick at t2 needs t1 free, pick at t3 needs t2 free, pick at bin2 needs bin1 free
                 (closing the fingers slides the bar 8 cm toward the robot, into the neighbour)
  bin guard      pick or place at t1/t2/t3 needs bin1 and bin2 free
                 (the hand and arm sweep over the bin row; 0/15 undisturbed picks in every approach variant tried)
  release rule   place at t2 needs t1 free, place at t3 needs t2 free (the release backs the hand up 10 cm toward the
                 robot and knocks the bar standing there: 3/3 disturbed in place_validation matrix; executor run p05: bars lost)
  no unstack     unstacking a free bar failed 0/3 even without neighbours (the base bar is dragged along) -> not offered
  no spare slot  c3 = (0.48,-0.05) is fine alone but picks and releases there knock over every other bar -> not used
The numbers behind each rule are in the docs/results notes. Edit the dictionaries below if a measurement changes.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SLOTS = ["t1", "t2", "t3", "bin1", "bin2"]
PICK_NEEDS_FREE = {"t1": ["bin1", "bin2"], "t2": ["t1", "bin1", "bin2"], "t3": ["t2", "bin1", "bin2"],
                   "bin1": [], "bin2": ["bin1"]}
PLACE_NEEDS_FREE = {"t1": ["bin1", "bin2"], "t2": ["t1", "bin1", "bin2"], "t3": ["t2", "bin1", "bin2"], "bin1": [], "bin2": []}


def build():
    out = [";; GENERATED by scripts/make_skill_domain.py -- do not edit by hand.",
           ";; Tabletop domain restricted to what the scripted skills execute reliably (see that script).",
           "(define (domain tabletop-skills)",
           "  (:requirements :strips :typing)",
           "  (:types item location)",
           f"  (:constants {' '.join(SLOTS)} - location)",
           "  (:predicates (at ?i - item ?p - location) (on ?i - item ?b - item) (clear ?i - item)",
           "               (free ?p - location) (holding ?i - item) (hand-empty))", ""]
    for s in SLOTS:
        guards = "".join(f" (free {g})" for g in PICK_NEEDS_FREE[s])
        out += [f"  (:action pick-{s}",
                "    :parameters (?i - item)",
                f"    :precondition (and (at ?i {s}) (clear ?i) (hand-empty){guards})",
                f"    :effect (and (holding ?i) (free {s}) (not (at ?i {s})) (not (clear ?i)) (not (hand-empty))))", ""]
    for s in SLOTS:
        guards = "".join(f" (free {g})" for g in PLACE_NEEDS_FREE[s])
        out += [f"  (:action place-{s}",
                "    :parameters (?i - item)",
                f"    :precondition (and (holding ?i) (free {s}){guards})",
                f"    :effect (and (at ?i {s}) (clear ?i) (hand-empty) (not (holding ?i)) (not (free {s}))))", ""]
    out += ["  (:action stack",
            "    :parameters (?i - item ?b - item)",
            "    :precondition (and (holding ?i) (clear ?b))",
            "    :effect (and (on ?i ?b) (clear ?i) (hand-empty) (not (holding ?i)) (not (clear ?b))))",
            ")", ""]
    return "\n".join(out)


if __name__ == "__main__":
    path = ROOT / "pddl" / "domain_skills.pddl"
    path.write_text(build(), encoding="utf-8")
    print(f"wrote {path}")
